import JSZip from 'jszip';
import { HistoryItem, LOGO_STYLES } from '../types';

/**
 * Creates an SVG XML string for a given logo base64
 */
function createSvgString(base64: string, mimeType: string, styleName: string): string {
  const size = 1024;
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  <title>Logo-go Emblem - ${styleName}</title>
  <desc>Generated by Logo-go Studio - Scalable Vector Emblem</desc>
  <defs>
    <clipPath id="logo-viewport-clip">
      <rect width="${size}" height="${size}" rx="0" ry="0" />
    </clipPath>
  </defs>
  <g id="logo-emblem" clip-path="url(#logo-viewport-clip)">
    <image href="data:${mimeType};base64,${base64}" width="${size}" height="${size}" preserveAspectRatio="xMidYMid meet" />
  </g>
</svg>`;
}

/**
 * Downloads a collection of logos packaged into a clean .zip bundle containing:
 * - High-Res PNG files
 * - Scalable Vector SVG files
 * - manifest.json with prompts, styles, and creation metadata
 */
export async function downloadBatchZip(
  items: HistoryItem[],
  customZipName?: string,
  onProgress?: (percent: number) => void
): Promise<void> {
  if (!items || items.length === 0) return;

  const zip = new JSZip();
  const folder = zip.folder('logos') || zip;
  const manifestData: Array<{
    filename: string;
    prompt: string;
    style: string;
    date: string;
    hasSvg: boolean;
  }> = [];

  for (let i = 0; i < items.length; i++) {
    const item = items[i];
    const indexStr = String(i + 1).padStart(2, '0');
    const safeStyle = (item.style || 'custom').toLowerCase().replace(/[^a-z0-9]/g, '-');
    const styleObj = LOGO_STYLES.find((s) => s.id === item.style);
    const styleName = styleObj ? styleObj.name : item.style || 'Custom';
    const baseName = `logo-${indexStr}-${safeStyle}`;

    // 1. Add PNG binary to ZIP
    if (item.logo?.base64) {
      folder.file(`${baseName}.png`, item.logo.base64, { base64: true });
    }

    // 2. Add SVG file (use pristine raw SVG if available, or generate scalable vector envelope)
    const svgData = item.logo?.svgContent && item.logo.svgContent.trim().startsWith('<svg')
      ? item.logo.svgContent.trim()
      : createSvgString(item.logo.base64, item.logo.mimeType || 'image/png', styleName);
    
    folder.file(`${baseName}.svg`, svgData);

    // 3. Record manifest metadata
    manifestData.push({
      filename: baseName,
      prompt: item.prompt,
      style: styleName,
      date: new Date(item.timestamp).toISOString(),
      hasSvg: true,
    });

    if (onProgress) {
      onProgress(Math.round(((i + 1) / items.length) * 50));
    }
  }

  // Add manifest.json and README.txt
  zip.file(
    'manifest.json',
    JSON.stringify(
      {
        studio: 'Logo-go Studio',
        exportedAt: new Date().toISOString(),
        totalItems: items.length,
        items: manifestData,
      },
      null,
      2
    )
  );

  zip.file(
    'README.txt',
    `LOGO-GO STUDIO EXPORT BUNDLE\n\nTotal Logos: ${items.length}\nDate: ${new Date().toLocaleDateString()}\n\nIncluded Formats:\n- .SVG: Universal scalable vector format for Figma, Adobe Illustrator, Canva, Web & Print\n- .PNG: High-resolution transparent raster graphic\n- manifest.json: Metadata record with prompts and style details\n`
  );

  // Generate zip file blob
  const zipBlob = await zip.generateAsync(
    {
      type: 'blob',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 },
    },
    (metadata) => {
      if (onProgress) {
        onProgress(50 + Math.round(metadata.percent * 0.5));
      }
    }
  );

  const url = URL.createObjectURL(zipBlob);
  const link = document.createElement('a');
  const now = new Date().toISOString().slice(0, 10);
  link.download = customZipName || `logo-go-bundle-${items.length}-logos-${now}.zip`;
  link.href = url;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
